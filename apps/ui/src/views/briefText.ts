export type BriefKey = keyof typeof en;

export function bt(lang: Lang, key: BriefKey, vars?: Record<string, string | number>): string {
  const text = (lang === "es" ? es : en)[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`));
}
