export const CHANGES_TEXT: Record<Lang, Record<Key, string>> = { en, es };

/** A label of the Changes view, with `{name}` filled from `vars`. */
export function ct(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return CHANGES_TEXT[lang][key].replace(/\{(\w+)\}/g, (_, n: string) =>
    String(vars[n] ?? `{${n}}`),
  );
}
